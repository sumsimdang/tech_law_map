def check_techlist(errors):
    T = TECHLIST
    for side in ("kc", "st"):
        n = sum(len(g["items"]) for g in T[side])
        if n != T["notices"][side]["total"]:
            errors.append(f"[고시 {side}] 항목 수 {n} ≠ {T['notices'][side]['total']}")
    def item(side, ref):
        f, _, i = ref.partition("/")
        g = next((g for g in T[side] if g["f"] == f), None)
        if not g or not (1 <= int(i) <= len(g["items"])):
            errors.append(f"[고시 {side}] {ref} 없음")
            return ""
        return g["items"][int(i) - 1]
    used_st, used_kc = set(), set()
    for pr in T["pairs"]:
        kt, st = item("kc", pr["kc"]), item("st", pr["st"])
        for h in pr["kh"]:
            if h not in kt:
                errors.append(f"[짝 {pr['t']}] 국가핵심기술 문구에 '{h}' 없음")
        for h in pr["sh"]:
            if h not in st:
                errors.append(f"[짝 {pr['t']}] 전략기술 문구에 '{h}' 없음")
        if pr["kc"] in used_kc or pr["st"] in used_st:
            errors.append(f"[짝 {pr['t']}] 중복 짝")
        used_kc.add(pr["kc"]); used_st.add(pr["st"])
    for ref in T["stOnlyNote"]:
        item("st", ref)
        if ref in used_st:
            errors.append(f"[전략기술 {ref}] 짝이 있는데 전략기술에만 있다고 표시")
    all_st = {f'{g["f"]}/{i + 1}' for g in T["st"] for i in range(len(g["items"]))}
    left = all_st - used_st - set(T["stOnlyNote"])
    if left:
        errors.append(f"[전략기술] 분류 안 된 항목: {sorted(left)}")


def article_text(l, a, v):
    arts = {x["k"]: x for x in GRAPH["articles"][l]}
    if a not in arts:
        raise KeyError(f"{l} {a} 조문 없음")
    head = arts[a]["x"]
    changed = VERS.get(l, {}).get("changed", {})
    if v == "inforce":
        return changed[a] if a in changed else head
    if v == "pending":
        if a not in changed:
            raise ValueError(f"{l} {a}: 시행 예정 개정이 없는데 pending으로 표시됨")
        return head
    return head


def check(obj, path, errors, count):
    if isinstance(obj, dict):
        if set(obj.keys()) >= {"l", "a", "q"}:
            try:
                txt = article_text(obj["l"], obj["a"], obj.get("v"))
                if obj["q"] not in txt:
                    errors.append(f"{path}: [{obj['l']} {obj['a']} {obj.get('v') or ''}] 구절 없음 → {obj['q'][:60]}")
                elif not obj.get("v"):
                    # 시행 예정 개정 조문인데 v가 없으면, 시행 중 문구에도 있는지 확인해 둔다
                    ch = VERS.get(obj["l"], {}).get("changed", {})
                    if obj["a"] in ch and obj["q"] not in ch[obj["a"]]:
                        errors.append(f"{path}: [{obj['l']} {obj['a']}] 최신 공포본에만 있는 구절인데 v 표시가 없음 → {obj['q'][:60]}")
                count[0] += 1
            except Exception as e:  # noqa
                errors.append(f"{path}: {e}")
            return
        for k, v in obj.items():
            check(v, f"{path}.{k}", errors, count)
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            check(v, f"{path}[{i}]", errors, count)


