lvmap = {}
for r in PAIRS:
    lvmap[(r["a"], r["b"])] = r["ab"]
    lvmap[(r["b"], r["a"])] = r["ba"]
for dg in DIAGRAMS:
    gx, gy = np.meshgrid(np.arange(1.5, dg["w"], 3), np.arange(1.5, dg["h"], 3))
    def m(s):
        if s["type"] == "rect":
            return (gx >= s["x"]) & (gx <= s["x"] + s["w"]) & (gy >= s["y"]) & (gy <= s["y"] + s["h"])
        return ((gx - s["cx"]) / s["rx"]) ** 2 + ((gy - s["cy"]) / s["ry"]) ** 2 <= 1
    ms = {s["key"]: m(s) for s in dg["shapes"]}
